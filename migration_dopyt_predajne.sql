-- ============================================================
-- DOPYT PREDAJNE: predajňa nahlási, že jej chýba tovar (mikiny, tričká...). Dopyt vyskočí všetkým určeným ľuďom,
-- prvý, kto ho prevezme, sa zapíše ako riešiteľ, potom sa vedie stav (objednané / vypísaná zákazka) až po "hotové".
-- Hotové dopyty ostávajú v histórii. Bezpečné spustiť opakovane, nič nemaže.
-- ============================================================
create table if not exists dopyty_predajne (
  id uuid primary key default gen_random_uuid(),
  cislo bigint generated by default as identity,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  created_by_id text,
  created_by_name text,
  predajna text,
  polozky text not null,
  priorita text not null default 'normal',        -- normal | urgent
  status text not null default 'novy',            -- novy | riesi | hotove | zrusene
  prevzal_id text,
  prevzal_meno text,
  prevzal_at timestamptz,
  cislo_zakazky text,
  udalosti jsonb not null default '[]'::jsonb,    -- [{at, kto, typ, text}]
  hotove_at timestamptz
);
create index if not exists dopyty_predajne_created_idx on dopyty_predajne (created_at desc);
create index if not exists dopyty_predajne_status_idx on dopyty_predajne (status);

alter table dopyty_predajne enable row level security;
drop policy if exists "prihlaseni plny pristup dopyty_predajne" on dopyty_predajne;
create policy "prihlaseni plny pristup dopyty_predajne" on dopyty_predajne for all
  using (auth.role() = 'authenticated') with check (auth.role() = 'authenticated');

-- Postup riešenia: stav je novy -> riesi -> hotove (alebo zrusene); popri tom sa nezávisle odškrtáva "textil objednaný" a "vypísaná zákazka" (cislo_zakazky)
alter table dopyty_predajne add column if not exists objednane boolean not null default false;
alter table dopyty_predajne add column if not exists objednane_at timestamptz;

-- Kto dostane upozornenie (zoznam ID zamestnancov). Prázdny zoznam = predvolene Master a Obchodníci.
create table if not exists dopyt_predajne_nastavenia (
  id int primary key default 1,
  ucastnici text[] not null default '{}',
  constraint dopyt_predajne_nastavenia_jeden check (id = 1)
);
insert into dopyt_predajne_nastavenia (id) values (1) on conflict (id) do nothing;
alter table dopyt_predajne_nastavenia enable row level security;
drop policy if exists "prihlaseni plny pristup dopyt_predajne_nastavenia" on dopyt_predajne_nastavenia;
create policy "prihlaseni plny pristup dopyt_predajne_nastavenia" on dopyt_predajne_nastavenia for all
  using (auth.role() = 'authenticated') with check (auth.role() = 'authenticated');

-- Realtime (okamžité vyskočenie dopytu a zmeny stavu)
do $$ begin
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and tablename = 'dopyty_predajne') then
    alter publication supabase_realtime add table dopyty_predajne;
  end if;
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and tablename = 'dopyt_predajne_nastavenia') then
    alter publication supabase_realtime add table dopyt_predajne_nastavenia;
  end if;
end $$;
